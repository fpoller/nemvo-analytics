<?php
/**
 * Hit collection endpoint.
 *
 * @package NemvoAnalytics
 */

namespace NemvoAnalytics;

defined( 'ABSPATH' ) || exit;

/**
 * Receives pageviews, engagement pings, events and verifications from the
 * tracker, enriches them (source, device, location, network, bot signals)
 * and writes them directly or through the queue.
 *
 * Payloads (JSON sent as text/plain):
 *  pv: { t:"pv", id, u:url, r:referrer, ti:title, w:screen width, tz, l:language, tp:touch, b:browser checks, c:{type,id,nf,sq} }
 *  e:  { t:"e",  id, d:engaged ms, s:scroll %, i:1 after mouse/touch/key/scroll }
 *  ev: { t:"ev", id, n:name, l:label }
 *  v:  { t:"v",  id, k:Cap token } or { t:"v", id, c:challenge, n:nonce }
 *
 * A pageview is answered with {"v":"cap"} or {"v":"pow","c":challenge} when
 * the visit has not proven itself yet; everything else with 204.
 */
class Collector {

	const NS       = 'nemvo/v1';
	const MAX_BODY = 8192;

	/**
	 * Events generated by the server itself; they do not count as interaction.
	 */
	const PASSIVE_EVENTS = array( '404', 'Site search' );

	/**
	 * Hits to write after the response has been sent.
	 *
	 * @var array[]
	 */
	private static $deferred = array();

	/**
	 * Register the public endpoint.
	 */
	public static function register_routes() {
		register_rest_route(
			self::NS,
			'/e',
			array(
				'methods'             => 'POST',
				'callback'            => array( __CLASS__, 'handle' ),
				'permission_callback' => '__return_true',
			)
		);
	}

	/**
	 * Handle one hit. Ignored hits get the same answer as accepted ones, so
	 * the tracker never retries and nothing reveals why a hit was dropped.
	 *
	 * @param \WP_REST_Request $request Request.
	 * @return \WP_REST_Response
	 */
	public static function handle( \WP_REST_Request $request ) {
		$response = self::empty_response();
		if ( ! Settings::get( 'tracking_enabled' ) ) {
			Diagnostics::log( '', 'ignored', 'tracking_off' );
			return $response;
		}
		$body = (string) $request->get_body();
		$data = '' === $body || strlen( $body ) > self::MAX_BODY ? null : json_decode( $body, true );
		// The tracker stopped in the browser; it only says so while "Check tracking" runs.
		if ( is_array( $data ) && 'x' === ( $data['t'] ?? '' ) ) {
			$reason = in_array( $data['r'] ?? '', array( 'gpc', 'dnt', 'ignore', 'error' ), true ) ? $data['r'] : 'error';
			Diagnostics::log( 'pv', 'ignored', 'client_' . $reason, array( 'path' => isset( $data['m'] ) ? sanitize_text_field( (string) $data['m'] ) : '' ) );
			return $response;
		}
		$pv   = is_array( $data ) && isset( $data['id'] ) && is_string( $data['id'] ) && preg_match( '/^[a-f0-9]{16}$/', $data['id'] ) ? $data['id'] : '';
		if ( '' === $pv || empty( $data['t'] ) || ! in_array( $data['t'], array( 'pv', 'e', 'ev', 'v' ), true ) ) {
			Diagnostics::log( '', 'ignored', 'payload' );
			return $response;
		}
		$signal = Privacy::opt_out_signal();
		if ( '' !== $signal ) {
			Diagnostics::log( $data['t'], 'ignored', $signal );
			return $response;
		}
		$ip = Privacy::client_ip();
		if ( Privacy::ip_excluded( $ip ) ) {
			Diagnostics::log( $data['t'], 'ignored', 'ip' );
			return $response;
		}
		$ua      = isset( $_SERVER['HTTP_USER_AGENT'] ) ? substr( sanitize_text_field( wp_unslash( $_SERVER['HTTP_USER_AGENT'] ) ), 0, 512 ) : '';
		$visitor = Privacy::visitor_hash( $ip, $ua );
		$now     = current_time( 'mysql' );
		$headers = array();
		foreach ( $request->get_headers() as $name => $values ) {
			$headers[ $name ] = is_array( $values ) ? (string) reset( $values ) : (string) $values;
		}
		Health::note_request( $headers );
		// A private address is a proxy's, not the visitor's: it says nothing about their network or location.
		$lookup_ip = Privacy::is_public( $ip ) ? $ip : '';

		switch ( $data['t'] ) {
			case 'pv':
				$hit = self::pageview( $data, $pv, $visitor, $now, $lookup_ip, $ua, $headers );
				return $hit ? self::store_pageview( $hit, $lookup_ip ) : $response;

			case 'e':
				Diagnostics::log( 'e', Queue::enabled() ? 'queued' : 'stored', '', array( 'interaction' => empty( $data['i'] ) ? 0 : 1, 'seconds' => isset( $data['d'] ) ? round( absint( $data['d'] ) / 1000 ) : 0 ) );
				self::defer(
					array(
						't'      => 'e',
						'at'     => $now,
						'pv'     => $pv,
						'ms'     => isset( $data['d'] ) ? absint( $data['d'] ) : 0,
						'scroll' => isset( $data['s'] ) ? absint( $data['s'] ) : 0,
						'flags'  => empty( $data['i'] ) ? 0 : Bot::INTERACTION,
					)
				);
				return $response;

			case 'ev':
				$name = isset( $data['n'] ) ? mb_substr( sanitize_text_field( (string) $data['n'] ), 0, 64 ) : '';
				if ( '' !== $name && ! in_array( $name, self::PASSIVE_EVENTS, true ) ) {
					Diagnostics::log( 'ev', Queue::enabled() ? 'queued' : 'stored', '', array( 'path' => $name ) );
					self::defer(
						array(
							't'     => 'ev',
							'at'    => $now,
							'pv'    => $pv,
							'name'  => $name,
							'label' => isset( $data['l'] ) ? mb_substr( sanitize_text_field( (string) $data['l'] ), 0, 255 ) : '',
						)
					);
				}
				return $response;

			case 'v':
				$flags = 0;
				if ( ! empty( $data['k'] ) && is_string( $data['k'] ) ) {
					$flags = Cap::verify( $data['k'] ) ? Bot::CAP : 0;
				} elseif ( isset( $data['c'], $data['n'] ) && is_string( $data['c'] ) && is_string( $data['n'] ) ) {
					$flags = Pow::verify( $data['c'], $data['n'], $pv ) ? Bot::POW : 0;
				}
				Diagnostics::log( 'v', $flags ? 'stored' : 'ignored', $flags ? '' : 'payload', array( 'path' => $flags & Bot::CAP ? 'Cap' : __( 'proof of work', 'nemvo-analytics' ) ) );
				if ( $flags ) {
					if ( Queue::enabled() ) {
						Queue::mark( 'ok', $visitor, 60 * (int) Settings::get( 'session_timeout' ) );
					}
					self::defer(
						array(
							't'     => 'v',
							'at'    => $now,
							'pv'    => $pv,
							'flags' => $flags,
						)
					);
				}
				return $response;
		}
		return $response;
	}

	/**
	 * Build an enriched pageview hit, or null when it is not for this site
	 * or excluded.
	 *
	 * @param array  $data    Payload.
	 * @param string $pv      Pageview id.
	 * @param string $visitor Visitor hash.
	 * @param string $now     Local datetime.
	 * @param string $ip      Client IP (memory only).
	 * @param string $ua      User agent.
	 * @param array  $headers Request headers.
	 * @return array|null
	 */
	private static function pageview( array $data, $pv, $visitor, $now, $ip, $ua, array $headers, $page = false ) {
		$parts = wp_parse_url( isset( $data['u'] ) ? (string) $data['u'] : '' );
		if ( ! $parts || empty( $parts['host'] ) || ! self::host_allowed( $parts['host'] ) ) {
			Diagnostics::log( 'pv', 'ignored', 'host', array( 'host' => $parts['host'] ?? '' ) );
			return null;
		}
		$path = self::clean_path( $parts['path'] ?? '/' );
		if ( Privacy::path_excluded( $path ) ) {
			Diagnostics::log( 'pv', 'ignored', 'path', array( 'path' => $path ) );
			return null;
		}
		$params = array();
		if ( ! empty( $parts['query'] ) ) {
			wp_parse_str( $parts['query'], $params );
		}
		$ctx      = isset( $data['c'] ) && is_array( $data['c'] ) ? $data['c'] : array();
		$referrer = isset( $data['r'] ) ? (string) $data['r'] : '';
		$is_404   = ! empty( $ctx['nf'] );
		$agent    = User_Agent::parse( $ua, ! empty( $data['tp'] ) );
		$flags    = Bot::request_flags( $ua, $data, $headers, $page );
		if ( $flags & ( Bot::UA_BOT | Bot::HEADLESS ) ) {
			$agent['browser'] = User_Agent::bot_name( $ua );
		}

		$ref404 = '';
		if ( $is_404 ) {
			$ref404 = self::host_allowed( (string) wp_parse_url( $referrer, PHP_URL_HOST ) ) ? self::clean_path( (string) wp_parse_url( $referrer, PHP_URL_PATH ) ) : Referrer::host_of( $referrer );
		}

		return array(
			't'       => 'pv',
			'at'      => $now,
			'pv'      => $pv,
			'visitor' => $visitor,
			'path'    => $path,
			'title'   => mb_substr( sanitize_text_field( isset( $data['ti'] ) ? (string) $data['ti'] : '' ), 0, 255 ),
			'post_id' => isset( $ctx['id'] ) ? absint( $ctx['id'] ) : 0,
			'type'    => isset( $ctx['type'] ) ? mb_substr( sanitize_key( (string) $ctx['type'] ), 0, 32 ) : '',
			'status'  => $is_404 ? 404 : 200,
			'src'     => Referrer::classify( $referrer, $params, (string) wp_parse_url( home_url(), PHP_URL_HOST ) ),
			'agent'   => $agent,
			'geo'     => Geo::locate( $ip, isset( $data['tz'] ) ? (string) $data['tz'] : '', isset( $data['l'] ) ? (string) $data['l'] : '' ),
			'net'     => Geo::network( $ip, false ),
			'lang'    => self::clean_language( isset( $data['l'] ) ? (string) $data['l'] : '' ),
			'screen'  => User_Agent::screen_class( isset( $data['w'] ) ? (int) $data['w'] : 0 ),
			'flags'   => $flags,
			'search'  => ! empty( $ctx['sq'] ) && Settings::get( 'track_search' ) ? mb_strtolower( mb_substr( sanitize_text_field( (string) $ctx['sq'] ), 0, 100 ) ) : '',
			'ref404'  => mb_substr( $ref404, 0, 255 ),
		);
	}

	/**
	 * Record the current page request on the server (template_redirect), so
	 * every view counts even when the browser never runs the tracker. The
	 * tracker then sends the returned id with its own hit, which confirms
	 * and completes this pageview instead of adding another one.
	 *
	 * Written without the reverse DNS lookup (that happens when the tracker
	 * confirms), so serving the page only costs a few small queries.
	 *
	 * @return string Pageview id for the tracker, or '' when not recorded.
	 */
	public static function server_hit() {
		$method  = isset( $_SERVER['REQUEST_METHOD'] ) ? sanitize_key( wp_unslash( $_SERVER['REQUEST_METHOD'] ) ) : 'get';
		$purpose = isset( $_SERVER['HTTP_SEC_PURPOSE'] ) ? sanitize_text_field( wp_unslash( $_SERVER['HTTP_SEC_PURPOSE'] ) ) : ( isset( $_SERVER['HTTP_PURPOSE'] ) ? sanitize_text_field( wp_unslash( $_SERVER['HTTP_PURPOSE'] ) ) : '' );
		// Prefetched and prerendered pages count when (and if) they are shown, through the tracker.
		if ( 'get' !== $method || false !== stripos( $purpose, 'prefetch' ) || false !== stripos( $purpose, 'prerender' ) ) {
			return '';
		}
		$uri  = isset( $_SERVER['REQUEST_URI'] ) ? esc_url_raw( wp_unslash( $_SERVER['REQUEST_URI'] ) ) : '/';
		$path = self::clean_path( (string) wp_parse_url( $uri, PHP_URL_PATH ) );
		$signal = Privacy::opt_out_signal();
		if ( '' !== $signal ) {
			Diagnostics::log( 'req', 'ignored', $signal, array( 'path' => $path ) );
			return '';
		}
		$ip = Privacy::client_ip();
		if ( Privacy::ip_excluded( $ip ) ) {
			Diagnostics::log( 'req', 'ignored', 'ip', array( 'path' => $path ) );
			return '';
		}
		$ua      = isset( $_SERVER['HTTP_USER_AGENT'] ) ? substr( sanitize_text_field( wp_unslash( $_SERVER['HTTP_USER_AGENT'] ) ), 0, 512 ) : '';
		$lang    = isset( $_SERVER['HTTP_ACCEPT_LANGUAGE'] ) ? sanitize_text_field( wp_unslash( $_SERVER['HTTP_ACCEPT_LANGUAGE'] ) ) : '';
		$headers = array(
			'accept_language' => $lang,
			'sec_fetch_mode'  => isset( $_SERVER['HTTP_SEC_FETCH_MODE'] ) ? sanitize_text_field( wp_unslash( $_SERVER['HTTP_SEC_FETCH_MODE'] ) ) : '',
		);
		$origin  = (string) preg_replace( '#^(https?://[^/]+).*$#', '$1', home_url() );
		$pv      = bin2hex( random_bytes( 8 ) );
		$data    = array(
			'u'  => $origin . $uri,
			'r'  => isset( $_SERVER['HTTP_REFERER'] ) ? esc_url_raw( wp_unslash( $_SERVER['HTTP_REFERER'] ) ) : '',
			'ti' => wp_get_document_title(),
			'l'  => trim( (string) strtok( $lang, ',;' ) ),
			'c'  => Tracker::context(),
		);
		$hit     = self::pageview( $data, $pv, Privacy::visitor_hash( $ip, $ua ), current_time( 'mysql' ), Privacy::is_public( $ip ) ? $ip : '', $ua, $headers, true );
		if ( ! $hit ) {
			return '';
		}
		$queued = Queue::enabled() && Queue::push( $hit );
		$stored = $queued || Processor::process( array( $hit ) );
		if ( Diagnostics::active() ) {
			$flags = Processor::$flags[ $pv ] ?? $hit['flags'];
			Diagnostics::log(
				'req',
				$stored ? ( $queued ? 'queued' : 'stored' ) : 'ignored',
				$stored ? '' : 'database',
				array(
					'path'     => $hit['path'],
					'score'    => Bot::score( $flags ),
					'flags'    => $flags,
					'network'  => $hit['net']['network'] ?? '',
					'provider' => $hit['net']['provider'] ?? '',
					'country'  => $hit['geo']['country'] ?? '',
					'browser'  => $hit['agent']['browser'] ?? '',
				)
			);
		}
		return $stored ? $pv : '';
	}

	/**
	 * Write or queue a pageview and tell the tracker whether to verify.
	 *
	 * @param array  $hit Hit.
	 * @param string $ip  Client IP (memory only, for the reverse DNS lookup of a new visit).
	 * @return \WP_REST_Response
	 */
	private static function store_pageview( array $hit, $ip ) {
		$verified = false;
		$queued   = false;
		if ( Queue::enabled() ) {
			// The worker never sees the IP, so look up the hostname now, once per visit.
			if ( Settings::get( 'rdns_lookup' ) && Queue::mark( 'seen', $hit['visitor'], 60 * (int) Settings::get( 'session_timeout' ) ) ) {
				$hit['net'] = Geo::network( $ip, true );
			}
			$verified = Queue::has( 'ok', $hit['visitor'] );
			$queued   = Queue::push( $hit );
		}
		$original = $hit['pv'];
		$flags    = $hit['flags'] | ( 'hosting' === ( $hit['net']['network'] ?? '' ) ? Bot::DATACENTER : 0 );
		if ( ! $queued ) {
			$enriched = $hit;
			$stored   = Processor::process(
				array( $hit ),
				static function ( $h ) use ( $ip, &$enriched ) {
					$h['net'] = Geo::network( $ip, true );
					$enriched = $h;
					return $h;
				}
			);
			$hit      = $enriched;
			$flags    = Processor::$flags[ $original ] ?? $flags;
			$verified = (bool) ( $flags & ( Bot::POW | Bot::CAP ) );
			if ( ! $stored ) {
				Diagnostics::log( 'pv', 'ignored', 'database', array( 'path' => $hit['path'] ) );
			}
		}
		if ( Diagnostics::active() ) {
			Diagnostics::log(
				'pv',
				$queued ? 'queued' : 'stored',
				'',
				array(
					'path'     => $hit['path'],
					'score'    => Bot::score( $flags ),
					'flags'    => $flags,
					'network'  => $hit['net']['network'] ?? '',
					'provider' => $hit['net']['provider'] ?? '',
					'company'  => $hit['net']['company'] ?? '',
					'country'  => $hit['geo']['country'] ?? '',
					'browser'  => $hit['agent']['browser'] ?? '',
				)
			);
		}

		// A cached copy of a page carried someone else's pageview id: the tracker continues with its own.
		$id    = Processor::$renamed[ $original ] ?? '';
		$reply = '' !== $id ? array( 'id' => $id ) : array();
		if ( ! $verified && ! ( $hit['flags'] & Bot::UA_BOT ) ) {
			if ( Cap::enabled() ) {
				$reply['v'] = 'cap';
			} elseif ( Settings::get( 'pow_enabled' ) ) {
				$reply['v'] = 'pow';
				$reply['c'] = Pow::challenge( '' !== $id ? $id : $hit['pv'] );
				$reply['b'] = Pow::BITS;
			}
		}
		if ( ! $reply ) {
			return self::empty_response();
		}
		$response = new \WP_REST_Response( $reply, 200 );
		$response->header( 'Cache-Control', 'no-store' );
		return $response;
	}

	/**
	 * Queue or write a hit after the response has gone out.
	 *
	 * @param array $hit Hit.
	 */
	private static function defer( array $hit ) {
		if ( Queue::enabled() && Queue::push( $hit ) ) {
			return;
		}
		if ( ! self::$deferred ) {
			add_action( 'shutdown', array( __CLASS__, 'flush' ), 0 );
		}
		self::$deferred[] = $hit;
	}

	/**
	 * Close the connection to the browser (where the server allows it), then write.
	 */
	public static function flush() {
		if ( function_exists( 'fastcgi_finish_request' ) ) {
			fastcgi_finish_request();
		} elseif ( function_exists( 'litespeed_finish_request' ) ) {
			litespeed_finish_request();
		}
		Processor::process( self::$deferred );
		self::$deferred = array();
	}

	/**
	 * The "nothing to do" answer.
	 *
	 * @return \WP_REST_Response
	 */
	private static function empty_response() {
		$response = new \WP_REST_Response( null, 204 );
		$response->header( 'Cache-Control', 'no-store' );
		return $response;
	}

	/**
	 * Only accept hits for this site's own host (www-insensitive).
	 *
	 * @param string $host Host from the reported URL.
	 * @return bool
	 */
	private static function host_allowed( $host ) {
		static $allowed = null;
		$strip = static function ( $h ) {
			return (string) preg_replace( '/^www\./', '', strtolower( (string) $h ) );
		};
		if ( null === $allowed ) {
			/**
			 * Filters the hosts the collector accepts hits for.
			 *
			 * @param string[] $allowed Hosts without www.
			 */
			$allowed = array_map( $strip, (array) apply_filters( 'nemvo_analytics_allowed_hosts', array( wp_parse_url( home_url(), PHP_URL_HOST ), wp_parse_url( site_url(), PHP_URL_HOST ) ) ) );
		}
		return '' !== $host && in_array( $strip( $host ), $allowed, true );
	}

	/**
	 * Normalise a URL path.
	 *
	 * @param string $path Raw path.
	 * @return string
	 */
	public static function clean_path( $path ) {
		$path = rawurldecode( (string) $path );
		$path = (string) preg_replace( '#/{2,}#', '/', $path );
		$path = '/' . ltrim( wp_strip_all_tags( $path ), '/' );
		return mb_substr( $path, 0, 255 );
	}

	/**
	 * Normalise a language tag to ll or ll-RR.
	 *
	 * @param string $lang Browser language.
	 * @return string
	 */
	private static function clean_language( $lang ) {
		if ( ! preg_match( '/^([a-z]{2,3})(?:[-_]([a-z]{2}))?/i', trim( $lang ), $m ) ) {
			return '';
		}
		return strtolower( $m[1] ) . ( isset( $m[2] ) ? '-' . strtoupper( $m[2] ) : '' );
	}
}
